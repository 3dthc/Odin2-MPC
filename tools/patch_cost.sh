#!/usr/bin/env bash
# Measure every factory patch's load (tools/patch_cost.cpp) on this machine and write src/presets/bank_cost.inc,
# scaled to the MPC Live II: on the device, Antarctica [RS] with 4 voices at audio rate (ECO Off) reads 80 % on the
# CPU meter, so every patch is scaled by the same factor. Takes a few minutes; run it on an otherwise idle machine.
set -euo pipefail
P="$(cd "$(dirname "$0")/.." && pwd)"
MV="${MPC_VST:-$P/../mpc-vst-plugins}"
O="${OBJ:-$(mktemp -d)}"
python3 "$MV/tools/gen_vst.py" "$P/vst/vst.json" --params-h >/dev/null
I="-I$P/src -I$P/src/odin/Source -I$P/src/odin/JuceLibraryCode -I$P/src/odin/libs/tuning-library -I$P/vst/build -I$MV/wrapper"
SRCS=$(cd "$P" && python3 -c "import json;print(' '.join(json.load(open('vst/vst.json'))['build']['sources']))")
for f in $SRCS; do echo "$P/$f"; done | xargs -P "$(nproc)" -I{} sh -c 'g++ -std=gnu++17 -O3 -fno-math-errno -DODIN_MPC_NO_BUDGET -w -c "{}" '"$I"' -o "'"$O"'/$(basename "{}").o"'
g++ -std=gnu++17 -O2 -w $I "$P/tools/patch_cost.cpp" "$O"/*.o -o "$O/patch_cost"
"$O/patch_cost" "${RUNS:-3}" | tee "$O/cost.txt"
python3 - "$O/cost.txt" "$P/src/presets/bank_cost.inc" <<'PY'
import sys
BLOCK_US = 128 / 44100 * 1e6
rows = [l.split(" ", 5) for l in open(sys.argv[1]).read().splitlines()]
ref = next(r for r in rows if r[5] == "Antarctica [RS]")
k = 80.0 / ((float(ref[1]) + 4 * float(ref[2])) / BLOCK_US * 100)   # x86 percent -> MPC Live II percent
pct = lambda us: max(1, round(float(us) / BLOCK_US * 100 * k * 10))   # tenths of a percent
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by tools/patch_cost.sh: per bank patch {per voice at audio rate, per voice at control rate,\n"
            " * no voice}, tenths of a percent of the MPC Live II block budget (factor %.3f from this machine). */\n" % k)
    for r in rows:
        off, ctrl = pct(r[2]), pct(r[3])
        f.write("{%d, %d, %d},   // %s\n" % (off, min(ctrl, off), pct(r[1]), r[5].replace("*/", "")))
print("factor %.3f; written %s" % (k, sys.argv[2]))
PY
