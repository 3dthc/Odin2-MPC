/* odin2-mpc dev tool: turn Odin's factory .odin presets into the bank compiled into the plugin.
 *
 * Each preset is loaded the way the plugin loads one (Odin's init patch first, then the preset, through Odin's own
 * patch reader and migration), and stored as the lines of its state that differ from the init patch.
 *   tools/make_bank <presets dir> <out dir>    (build with tools/make_bank.sh)
 * Writes <out>/bank_data.inc (C++ initialisers) and <out>/bank.json (names, for the parameter list). */
#include "odin_state.h"
#include <algorithm>
#include <dirent.h>
#include <fstream>
#include <sstream>
#include <sys/stat.h>

static std::string readFile(const std::string &path) {
    std::ifstream f(path, std::ios::binary);
    std::stringstream ss;
    ss << f.rdbuf();
    return ss.str();
}

static std::vector<std::string> listDir(const std::string &dir, bool dirs) {
    std::vector<std::string> out;
    DIR *d = opendir(dir.c_str());
    if (!d) return out;
    while (dirent *e = readdir(d)) {
        std::string n = e->d_name;
        if (n[0] == '.') continue;
        struct stat st;
        if (stat((dir + "/" + n).c_str(), &st)) continue;
        if (dirs == S_ISDIR(st.st_mode)) out.push_back(n);
    }
    closedir(d);
    std::sort(out.begin(), out.end());
    return out;
}

static std::string cstr(const std::string &s) {
    std::string o = "\"";
    for (char c : s) {
        if (c == '\\' || c == '"') o += '\\', o += c;
        else if (c == '\n') o += "\\n\"\n        \"";
        else o += c;
    }
    return o + "\"";
}

static std::string jstr(const std::string &s) {
    std::string o = "\"";
    for (char c : s) { if (c == '\\' || c == '"') o += '\\'; o += c; }
    return o + "\"";
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: make_bank <presets dir> <out dir>\n"); return 2; }
    std::string src = argv[1], out = argv[2];
    auto *p = new OdinAudioProcessor();
    p->prepare(44100);
    auto loadInit = [&]() { p->loadPatchFromMemory(BinaryData::init_patch_odin, BinaryData::init_patch_odinSize); };
    loadInit();
    OdinMPC::Lines init = OdinMPC::snapshot(*p);

    std::ofstream inc(out + "/bank_data.inc"), js(out + "/bank.json");
    inc << "/* Generated by tools/make_bank from Odin 2's factory presets (GPL-3.0-or-later, as Odin 2):\n"
           " * category, name, the lines of the preset's state that differ from Odin's init patch. */\n";
    inc << "    {\"Init\", \"Init Patch\", \"\"},\n";
    js << "{\"presets\": [\n  {\"category\": \"Init\", \"name\": \"Init Patch\"}";
    int n = 1, total = 0, failed = 0;
    size_t longest = 0;
    for (auto &cat : listDir(src, true)) {
        for (auto &file : listDir(src + "/" + cat, false)) {
            if (file.size() < 6 || file.substr(file.size() - 5) != ".odin") continue;
            std::string data = readFile(src + "/" + cat + "/" + file);
            loadInit();
            if (!p->loadPatchFromMemory(data.data(), data.size())) {
                fprintf(stderr, "skipped (unreadable or newer): %s/%s\n", cat.c_str(), file.c_str());
                failed++;
                continue;
            }
            OdinMPC::Lines d = OdinMPC::diff(init, OdinMPC::snapshot(*p));
            std::string text = OdinMPC::join(d);
            longest = std::max(longest, text.size());
            total += (int)text.size();
            std::string name = file.substr(0, file.size() - 5);
            inc << "    {" << cstr(cat) << ", " << cstr(name) << ",\n        " << cstr(text) << "},\n";
            js << ",\n  {\"category\": " << jstr(cat) << ", \"name\": " << jstr(name) << "}";
            n++;
        }
    }
    js << "\n]}\n";
    printf("%d presets (%d skipped), %d bytes of state, longest %zu\n", n, failed, total, longest);
    return failed ? 1 : 0;
}
